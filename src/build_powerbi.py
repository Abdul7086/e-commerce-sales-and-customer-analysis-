"""Generate a source-controlled Power BI Project (PBIP/PBIR/TMDL).

Run the data pipeline first. The generated M parameter points at this checkout;
rerunning this builder after cloning rewrites that path for the new location.
"""
from pathlib import Path
import json
import re

ROOT = Path(__file__).resolve().parents[1]
PROJECT = "Superstore Sales Analysis"
REPORT_DIR = ROOT / f"{PROJECT}.Report"
MODEL_DIR = ROOT / f"{PROJECT}.SemanticModel"
REPORT_DEF = REPORT_DIR / "definition"
PAGES_DIR = REPORT_DEF / "pages"
