TABLES_DIR = MODEL_DEF / "tables"

def write_json(path, obj):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(obj, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

def write_text(path, content):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content.rstrip() + "\n", encoding="utf-8")

def tmdl_quote(s):
    return "'" + s.replace("'", "''") + "'" if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", s) else s

def column(name, source, dtype, hidden=False, sort=None, category=None):
    out = f"\n\tcolumn {tmdl_quote(name)}\n\t\tdataType: {dtype}\n\t\tsourceColumn: {source}"
    if hidden:
        out += "\n\t\tisHidden"
    if sort:
        out += f"\n\t\tsortByColumn: {tmdl_quote(sort)}"
    if category:
        out += f"\n\t\tdataCategory: {category}"
    return out

def table_file(name, columns, partition, measures=""):
    cols = "".join(column(*c) for c in columns)
    return f"table {tmdl_quote(name)}\n{cols}\n{measures}\n\tpartition {tmdl_quote(name)} = m\n\t\tmode: import\n\t\tsource = {partition}\n"

def col(entity, name):
    return {"Column": {"Expression": {"SourceRef": {"Entity": entity}}, "Property": name}}

def measure(entity, name):
    return {"Measure": {"Expression": {"SourceRef": {"Entity": entity}}, "Property": name}}

def proj(field, query_ref, display=None):
    p = {"field": field, "queryRef": query_ref}
    if display:
        p["displayName"] = display
    return p

def projections(**roles):
    return {r: {"projections": ps} for r, ps in roles.items()}

def literal(value):
    return {"expr": {"Literal": {"Value": value}}}

def title_object(text):
    return {"title": [{"properties": {
        "show": literal("true"),
        "text": literal("'" + text.replace("'", "''") + "'"),
        "fontSize": literal("12D"),
        "fontColor": {"solid": {"color": "#17324D"}}
    }}]}

VISUAL_SCHEMA = "https://developer.microsoft.com/json-schemas/fabric/item/report/definition/visualContainer/2.7.0/schema.json"

def visual(name, vtype, pos, roles=None, title=None, extra=None, query_options=None):
    conf = {"visualType": vtype, "drillFilterOtherVisuals": True}
    if roles is not None:
        conf["query"] = {"queryState": roles}
        if query_options:
            conf["query"]["sortDefinition"] = query_options
    if title:
        conf["visualContainerObjects"] = title_object(title)
    conf.update(extra or {})
    out = {
        "$schema": VISUAL_SCHEMA,
        "name": name,
        "position": {**pos, "z": 1000 + len(list(VISUALS_DIR.glob("*/visual.json"))) * 1000, "tabOrder": len(list(VISUALS_DIR.glob("*/visual.json")))},
        "visual": conf,
    }
    write_json(VISUALS_DIR / name / "visual.json", out)

def make_pbip():
    # Remove only files generated by this builder, keeping other project assets intact.
    for d in (VISUALS_DIR, TABLES_DIR):
        d.mkdir(parents=True, exist_ok=True)
        for f in d.rglob("*.json" if d == VISUALS_DIR else "*.tmdl"):
            f.unlink()

    write_json(ROOT / f"{PROJECT}.pbip", {
        "$schema": "https://developer.microsoft.com/json-schemas/fabric/pbip/pbipProperties/1.0.0/schema.json",
        "version": "1.0",
        "artifacts": [{"report": {"path": f"{PROJECT}.Report"}}],
        "settings": {"enableAutoRecovery": True},
    })
    write_json(REPORT_DIR / "definition.pbir", {
        "$schema": "https://developer.microsoft.com/json-schemas/fabric/item/report/definitionProperties/2.0.0/schema.json",
        "version": "4.0",
        "datasetReference": {"byPath": {"path": f"../{PROJECT}.SemanticModel"}},
    })
    write_json(MODEL_DIR / "definition.pbism", {
        "$schema": "https://developer.microsoft.com/json-schemas/fabric/item/semanticModel/definitionProperties/1.0.0/schema.json",
        "version": "4.2",
        "settings": {"qnaEnabled": True},
    })

    write_json(REPORT_DEF / "version.json", {
        "$schema": "https://developer.microsoft.com/json-schemas/fabric/item/report/definition/versionMetadata/1.0.0/schema.json",
        "version": "1.0.0",
    })
    write_json(REPORT_DEF / "report.json", {
        "$schema": "https://developer.microsoft.com/json-schemas/fabric/item/report/definition/report/1.0.0/schema.json",
        "layoutOptimization": "None",
        "themeCollection": {"baseTheme": {"name": "CY24SU06", "reportVersionAtImport": "5.55", "type": "SharedResources"}},
        "settings": {"useStylableVisualContainerHeader": True},
    })
    write_json(PAGES_DIR / "pages.json", {
        "$schema": "https://developer.microsoft.com/json-schemas/fabric/item/report/definition/pagesMetadata/1.0.0/schema.json",
        "pageOrder": [PAGE_NAME], "activePageName": PAGE_NAME,
    })
    write_json(PAGE_DIR / "page.json", {
        "$schema": "https://developer.microsoft.com/json-schemas/fabric/item/report/definition/page/2.0.0/schema.json",
        "name": PAGE_NAME,
        "displayName": "Sales Overview",
        "displayOption": "FitToPage",
        "width": 1280,
        "height": 720,
    })

    title_pos = {"x": 10, "y": 14, "width": 405, "height": 101}
    textbox = {
        "$schema": VISUAL_SCHEMA,
        "name": "DashboardTitle",
        "position": {**title_pos, "z": 1000, "tabOrder": 0},
        "visual": {"visualType": "textbox", "objects": {"general": [{"properties": {"paragraphs": [{"textRuns": [{"value": "SUPERSTORE SALES & CUSTOMER ANALYSIS", "textStyle": {"fontSize": "25pt", "fontWeight": "bold", "color": "#17324D"}}, {"value": "\nSales, profit and customer performance | 2014–2017", "textStyle": {"fontSize": "11pt", "color": "#476A6F"}}]}]}}]}, "drillFilterOtherVisuals": True},
    }
    write_json(VISUALS_DIR / "DashboardTitle" / "visual.json", textbox)

    dims = {"FactOrderLine": "FactOrderLine"}
    # Reference visual mapping: four KPI cards, profit trend, product/customer/state
    # charts, two slicers, city map, and two quantity breakdown donuts.
    specs = [
        ("ProfitByMonth", "columnChart", {"x": 687, "y": 435, "width": 579, "height": 276}, projections(Category=[proj(col("DimDate", "Year-Month"), "DimDate.Year-Month")], Y=[proj(measure("FactOrderLine", "Profit"), "FactOrderLine.Profit")]), "Profit by Month", {"sort": [{"field": col("DimDate", "Year-Month"), "direction": "Ascending"}], "isDefaultSort": False}),
        ("ProfitBySubCategory", "columnChart", {"x": 687, "y": 115, "width": 219, "height": 305}, projections(Category=[proj(col("DimProduct", "Sub-Category"), "DimProduct.Sub-Category")], Y=[proj(measure("FactOrderLine", "Profit"), "FactOrderLine.Profit")]), "Profit by Sub-Category", None),
        ("QuantityByCategory", "donutChart", {"x": 344, "y": 494, "width": 332, "height": 216}, projections(Category=[proj(col("DimProduct", "Category"), "DimProduct.Category")], Y=[proj(measure("FactOrderLine", "Quantity"), "FactOrderLine.Quantity")]), "Quantity by Category", None),
        ("QuantityByShipMode", "donutChart", {"x": 347, "y": 266, "width": 329, "height": 216}, projections(Category=[proj(col("DimShipMode", "Ship Mode"), "DimShipMode.Ship Mode")], Y=[proj(measure("FactOrderLine", "Quantity"), "FactOrderLine.Quantity")]), "Quantity by Ship Mode", None),
        ("SalesByState", "barChart", {"x": 10, "y": 266, "width": 325, "height": 216}, projections(Category=[proj(col("DimGeography", "State"), "DimGeography.State")], Y=[proj(measure("FactOrderLine", "Sales"), "FactOrderLine.Sales")], Tooltips=[proj(measure("FactOrderLine", "Profit"), "FactOrderLine.Profit")]), "Sales by State", None),
        ("TopCustomers", "columnChart", {"x": 10, "y": 494, "width": 325, "height": 216}, projections(Category=[proj(col("DimCustomer", "Customer Name"), "DimCustomer.Customer Name")], Y=[proj(measure("FactOrderLine", "Sales"), "FactOrderLine.Sales")], Tooltips=[proj(measure("FactOrderLine", "Profit"), "FactOrderLine.Profit")]), "Customer Sales (sort by Sales; filter Top 10)", {"sort": [{"field": measure("FactOrderLine", "Sales"), "direction": "Descending"}], "isDefaultSort": False}),
        ("QuarterSlicer", "slicer", {"x": 423, "y": 14, "width": 253, "height": 101}, projections(Values=[proj(col("DimDate", "Quarter"), "DimDate.Quarter")]), "Order Quarter", None),
        ("StateSlicer", "slicer", {"x": 687, "y": 14, "width": 217, "height": 89}, projections(Values=[proj(col("DimGeography", "State"), "DimGeography.State")]), "State", None),
        ("SalesByCity", "map", {"x": 919, "y": 14, "width": 348, "height": 406}, projections(Category=[proj(col("DimGeography", "City"), "DimGeography.City")], Size=[proj(measure("FactOrderLine", "Orders"), "FactOrderLine.Orders")], Tooltips=[proj(measure("FactOrderLine", "Quantity"), "FactOrderLine.Quantity"), proj(measure("FactOrderLine", "Profit"), "FactOrderLine.Profit")]), "Sales by City (bubble size = Orders)", None),
    ]
    for i, (name, vtype, pos, roles, title, sorting) in enumerate(specs):
        visual(name, vtype, pos, roles, title, query_options=sorting)
    top_customer_path = VISUALS_DIR / "TopCustomers" / "visual.json"
    top_customer_visual = json.loads(top_customer_path.read_text(encoding="utf-8"))
    top_customer_visual["filterConfig"] = {"filters": [{
        "name": "Top10CustomersBySales",
        "field": col("DimCustomer", "Customer Name"),
        "type": "TopN",
        "filter": {
            "Version": 2,
            "From": [{"Name": "c", "Entity": "DimCustomer", "Type": 0}, {"Name": "f", "Entity": "FactOrderLine", "Type": 0}],
            "Where": [{"Target": [col("DimCustomer", "Customer Name")], "Condition": {"VisualTopN": {"ItemCount": 10}}}],
        },
        "howCreated": "User",
    }]}
    write_json(top_customer_path, top_customer_visual)
    kpis = [
        ("SalesCard", "Sales", "Sales", 10),
        ("ProfitCard", "Profit", "Profit", 178),
        ("QuantityCard", "Quantity", "Quantity", 347),
        ("AOVCard", "Average Order Value", "Average Order Value", 516),
    ]
    for name, title, measure_name, x in kpis:
        roles = projections(Values=[proj(measure("FactOrderLine", measure_name), f"FactOrderLine.{measure_name}")])
        visual(name, "card", {"x": x, "y": 128, "width": 158 if x < 516 else 160, "height": 125}, roles, title)

    # TMDL semantic model. Shared Power Query expressions load the cleaned export
    # once logically and derive dimensions at their proper business-key grain.
    clean_types = "{{\"row_id\", Int64.Type}, {\"order_date\", type date}, {\"ship_date\", type date}, {\"sales\", type number}, {\"quantity\", Int64.Type}, {\"discount\", type number}, {\"profit\", type number}, {\"ship_days\", Int64.Type}, {\"order_year\", Int64.Type}, {\"order_month\", Int64.Type}, {\"is_valid\", type logical}}"
    mclean = f'''let
    Raw = Csv.Document(File.Contents(pProjectRoot & "\\data\\processed\\superstore_clean.csv"), [Delimiter=",", Encoding=65001, QuoteStyle=QuoteStyle.Csv]),
    Headers = Table.PromoteHeaders(Raw, [PromoteAllScalars=true]),
    Typed = Table.TransformColumnTypes(Headers, {clean_types}, "en-US"),
    PostalText = Table.TransformColumnTypes(Typed, {{{{\"postal_code\", type text}}}}, "en-US"),
    GeographyKey = Table.AddColumn(PostalText, "geography_key", each Text.Combine({{[country], [region], [state], [city]}}, "|"), type text)
in
    GeographyKey'''
    expressions = f'''expression pProjectRoot = "{str(ROOT).replace(chr(92) + chr(92), chr(92))}" meta [IsParameterQuery=true, Type="Text", IsParameterQueryRequired=true]

expression CleanedRows = ```
{mclean}
```

expression FactRows = Table.SelectRows(CleanedRows, each [is_valid] = true)

expression CustomerRows = Table.Group(FactRows, {{"customer_id"}}, {{{{"customer_name", each List.First(List.RemoveNulls([customer_name])), type text}}, {{"segment", each List.First(List.RemoveNulls([segment])), type text}}}})

expression ProductRows = Table.Group(FactRows, {{"product_id"}}, {{{{"product_name", each List.First(List.RemoveNulls([product_name])), type text}}, {{"category", each List.First(List.RemoveNulls([category])), type text}}, {{"sub_category", each List.First(List.RemoveNulls([sub_category])), type text}}}})

expression ShipModeRows = Table.Distinct(Table.SelectColumns(FactRows, {{"ship_mode"}}))

expression GeographyRows = Table.Distinct(Table.SelectColumns(FactRows, {{"geography_key", "country", "region", "state", "city"}}))

expression DateRows = ```
let
    Source = Table.TransformColumnTypes(FactRows, {{{{"order_date", type date}}}}, "en-US"),
    FirstDate = List.Min(Source[order_date]),
    LastDate = List.Max(Source[order_date]),
    Dates = List.Dates(FirstDate, Duration.Days(LastDate - FirstDate) + 1, #duration(1, 0, 0, 0)),
    Base = Table.FromList(Dates, Splitter.SplitByNothing(), {{"Date"}}),
    AddYear = Table.AddColumn(Base, "Year", each Date.Year([Date]), Int64.Type),
    AddMonthNumber = Table.AddColumn(AddYear, "Month Number", each Date.Month([Date]), Int64.Type),
    AddMonth = Table.AddColumn(AddMonthNumber, "Month", each Date.ToText([Date], "MMM", "en-US"), type text),
    AddYearMonth = Table.AddColumn(AddMonth, "Year-Month", each Date.ToText([Date], "yyyy-MM", "en-US"), type text),
    AddYearMonthSort = Table.AddColumn(AddYearMonth, "Year-Month Sort", each Date.Year([Date]) * 100 + Date.Month([Date]), Int64.Type),
    AddQuarterNumber = Table.AddColumn(AddYearMonthSort, "Quarter Number", each Date.QuarterOfYear([Date]), Int64.Type),
    AddQuarter = Table.AddColumn(AddQuarterNumber, "Quarter", each "Q" & Text.From([Quarter Number]) & " " & Text.From([Year]), type text),
    AddYearQuarterSort = Table.AddColumn(AddQuarter, "Year-Quarter Sort", each [Year] * 10 + [Quarter Number], Int64.Type)
in
    AddYearQuarterSort
```'''
    write_text(MODEL_DEF / "expressions.tmdl", expressions)
    write_text(MODEL_DEF / "database.tmdl", "database Superstore\n\tcompatibilityLevel: 1604\n\tmodel Model")
    write_text(MODEL_DEF / "model.tmdl", "model Model\n\tculture: en-US\n\tsourceQueryCulture: en-US\n\tdefaultPowerBIDataSourceVersion: powerBI_V3\n\tannotation __PBI_TimeIntelligenceEnabled = 1")
    write_text(MODEL_DEF / "relationships.tmdl", '''relationship Customer
\tfromColumn: FactOrderLine.'Customer ID'
\ttoColumn: DimCustomer.'Customer ID'

relationship Product
\tfromColumn: FactOrderLine.'Product ID'
\ttoColumn: DimProduct.'Product ID'

relationship Geography
\tfromColumn: FactOrderLine.'Geography Key'
\ttoColumn: DimGeography.'Geography Key'

relationship ShipMode
\tfromColumn: FactOrderLine.'Ship Mode'
\ttoColumn: DimShipMode.'Ship Mode'

relationship OrderDate
\tfromColumn: FactOrderLine.'Order Date'
\ttoColumn: DimDate.Date''')

    fact_columns = [
        ("Row ID", "row_id", "int64", True), ("Order ID", "order_id", "string", False), ("Order Date", "order_date", "dateTime", False), ("Ship Date", "ship_date", "dateTime", False),
        ("Ship Mode", "ship_mode", "string", True), ("Customer ID", "customer_id", "string", True), ("Customer Name", "customer_name", "string", False), ("Segment", "segment", "string", False),
        ("Country", "country", "string", True), ("City", "city", "string", True), ("State", "state", "string", True), ("Postal Code", "postal_code", "string", True), ("Region", "region", "string", False),
        ("Product ID", "product_id", "string", True), ("Category", "category", "string", False), ("Sub-Category", "sub_category", "string", False), ("Product Name", "product_name", "string", False),
        ("Sales", "sales", "double", False), ("Quantity", "quantity", "int64", False), ("Discount", "discount", "double", False), ("Profit", "profit", "double", False), ("Ship Days", "ship_days", "int64", False),
        ("Geography Key", "geography_key", "string", True), ("Order Year", "order_year", "int64", True), ("Order Month", "order_month", "int64", True), ("Order Month Name", "order_month_name", "string", True), ("Order Quarter", "order_quarter", "string", True), ("Is Valid", "is_valid", "boolean", True),
    ]
    measures = '''\tmeasure Sales = SUM(FactOrderLine[Sales])\n\t\tformatString: $#,0.00;($#,0.00);$#,0.00
\n\tmeasure Profit = SUM(FactOrderLine[Profit])\n\t\tformatString: $#,0.00;($#,0.00);$#,0.00
\n\tmeasure Quantity = SUM(FactOrderLine[Quantity])\n\t\tformatString: #,0
\n\tmeasure Orders = DISTINCTCOUNT(FactOrderLine[Order ID])\n\t\tformatString: #,0
\n\tmeasure Customers = DISTINCTCOUNT(DimCustomer[Customer ID])\n\t\tformatString: #,0
\n\tmeasure 'Average Order Value' = DIVIDE([Sales], [Orders])\n\t\tformatString: $#,0.00
\n\tmeasure 'Profit Margin' = DIVIDE([Profit], [Sales])\n\t\tformatString: 0.0%;-0.0%;0.0%
\n\tmeasure 'Sales YoY %' = VAR PriorYearSales = CALCULATE([Sales], SAMEPERIODLASTYEAR(DimDate[Date])) RETURN DIVIDE([Sales] - PriorYearSales, PriorYearSales)\n\t\tformatString: 0.0%;-0.0%;0.0%
\n\tmeasure 'Profit YoY %' = VAR PriorYearProfit = CALCULATE([Profit], SAMEPERIODLASTYEAR(DimDate[Date])) RETURN DIVIDE([Profit] - PriorYearProfit, ABS(PriorYearProfit))\n\t\tformatString: 0.0%;-0.0%;0.0%
\n\tmeasure 'Average Discount' = AVERAGE(FactOrderLine[Discount])\n\t\tformatString: 0.0%
\n\tmeasure 'Loss Making Lines' = CALCULATE(COUNTROWS(FactOrderLine), FactOrderLine[Profit] < 0)\n\t\tformatString: #,0
\n\tmeasure 'Loss Line %' = DIVIDE([Loss Making Lines], COUNTROWS(FactOrderLine))\n\t\tformatString: 0.0%
\n\tmeasure 'Sales per Customer' = DIVIDE([Sales], [Customers])\n\t\tformatString: $#,0.00'''
    write_text(TABLES_DIR / "FactOrderLine.tmdl", table_file("FactOrderLine", fact_columns, "FactRows", measures))
    write_text(TABLES_DIR / "DimCustomer.tmdl", table_file("DimCustomer", [("Customer ID", "customer_id", "string", False), ("Customer Name", "customer_name", "string", False), ("Segment", "segment", "string", False)], "CustomerRows"))
    write_text(TABLES_DIR / "DimProduct.tmdl", table_file("DimProduct", [("Product ID", "product_id", "string", False), ("Product Name", "product_name", "string", False), ("Category", "category", "string", False), ("Sub-Category", "sub_category", "string", False)], "ProductRows"))
    write_text(TABLES_DIR / "DimShipMode.tmdl", table_file("DimShipMode", [("Ship Mode", "ship_mode", "string", False)], "ShipModeRows"))
    write_text(TABLES_DIR / "DimGeography.tmdl", table_file("DimGeography", [("Geography Key", "geography_key", "string", True), ("Country", "country", "string", False, None, "Country"), ("Region", "region", "string", False), ("State", "state", "string", False, None, "StateOrProvince"), ("City", "city", "string", False, None, "City")], "GeographyRows"))
